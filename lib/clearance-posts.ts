const STORAGE_KEY = "oladeck_clearance_posts";

export function getClearancePosts(): ClearancePost[] {
  if (typeof window === "undefined") return initialClearancePosts;
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (!stored) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(initialClearancePosts));
      return initialClearancePosts;
    }
    return JSON.parse(stored);
  } catch {
    return initialClearancePosts;
  }
}

export function saveClearancePost(newPost: ClearancePost): ClearancePost[] {
  const current = getClearancePosts();
  const updated = [newPost, ...current];
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  }
  return updated;
}

export function deleteClearancePost(id: string): ClearancePost[] {
  const current = getClearancePosts();
  const updated = current.filter((p) => p.id !== id);
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  }
  return updated;
}

export function toggleLikeClearancePost(id: string): ClearancePost[] {
  const current = getClearancePosts();
  const updated = current.map((p) => (p.id === id ? { ...p, likesCount: p.likesCount + 1 } : p));
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  }
  return updated;
}
